/**
 * Email utility — Brevo (Sendinblue) Transactional Email API
 *
 * Sends emails via the Brevo REST API instead of Nodemailer/Gmail SMTP.
 * Requires BREVO_API_KEY and BREVO_SENDER_EMAIL in .env
 */

const BREVO_API_URL = "https://api.brevo.com/v3/smtp/email";

function getConfig() {
  const apiKey = process.env.BREVO_API_KEY;
  const senderEmail = process.env.BREVO_SENDER_EMAIL || "noreply@taskmanager.com";
  const senderName = process.env.BREVO_SENDER_NAME || "Task Manager";

  if (!apiKey) {
    throw new Error(
      "Brevo API key not configured. Please set BREVO_API_KEY in your .env file."
    );
  }

  return { apiKey, senderEmail, senderName };
}

/**
 * Low-level helper: send a transactional email via Brevo API
 */
async function brevoSend({ to, subject, htmlContent }) {
  const { apiKey, senderEmail, senderName } = getConfig();

  const response = await fetch(BREVO_API_URL, {
    method: "POST",
    headers: {
      accept: "application/json",
      "content-type": "application/json",
      "api-key": apiKey,
    },
    body: JSON.stringify({
      sender: { name: senderName, email: senderEmail },
      to: [{ email: to }],
      subject,
      htmlContent,
    }),
  });

  if (!response.ok) {
    const errorBody = await response.text();
    throw new Error(
      `Brevo API error (${response.status}): ${errorBody}`
    );
  }

  return response.json();
}

